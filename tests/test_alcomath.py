"""
alcomath.py must produce the same numbers as the previous Node.js implementation.

golden_alcomath.json was generated by running the original app/lib/alcomath.js and
app/constants.js with a fixed clock (see the git history for the Node.js sources).
"""

import json
from datetime import UTC
from pathlib import Path
from types import SimpleNamespace

import pytest

from blakkisvuohi import alcomath, constants

GOLDEN = json.loads((Path(__file__).parent / "golden_alcomath.json").read_text())
NOW = GOLDEN["now"]


def _case_id(case):
    u = case["user"]
    return f"{u['gender']}-{u['weight']}kg-{len(case['drinks'])}drinks"


def _user(data):
    return SimpleNamespace(**data)


def _drinks(case):
    return [SimpleNamespace(**d) for d in case["drinks"]]


@pytest.mark.parametrize("case", GOLDEN["cases"], ids=_case_id)
def test_ebac_matches_nodejs_implementation(case):
    ebac = alcomath.calculate_ebac(_user(case["user"]), _drinks(case), now=NOW)
    expected = case["ebac"]
    assert ebac.permilles == pytest.approx(expected["permilles"], abs=1e-9)
    assert ebac.permilles_30min == pytest.approx(expected["permilles30Min"], abs=1e-9)
    assert ebac.grams == pytest.approx(expected["grams"], abs=1e-9)
    assert ebac.burn_hours == pytest.approx(expected["burn_hours"], abs=1e-9)


@pytest.mark.parametrize("case", [c for c in GOLDEN["cases"] if c["drinks"]], ids=_case_id)
def test_hourly_ebac_matches_nodejs_implementation(case):
    hourly = alcomath.calculate_ebac_by_hour(
        _user(case["user"]), _drinks(case), 24, 12, now=NOW, tz=UTC
    )
    assert len(hourly) == len(case["hourly"]) == 37
    for got, expected in zip(hourly, case["hourly"], strict=True):
        assert got.permilles == pytest.approx(expected["permilles"], abs=1e-9)
        assert got.time * 1000 == expected["time"]


def test_constants_match_nodejs_implementation():
    expected = GOLDEN["consts"]
    assert constants.KALJA033 == expected["kalja033"]
    assert constants.KALJA05 == expected["kalja05"]
    assert constants.SINGLE_DRINK_ALCOHOL_LIMIT == expected["limit"]
    assert {k: v.mg for k, v in constants.MILDS.items()} == expected["milds"]
    assert {k: v.mg for k, v in constants.BOOZE.items()} == expected["booze"]


def test_no_drinks_means_sober():
    ebac = alcomath.calculate_ebac(SimpleNamespace(gender="mies", height=180, weight=80), [], NOW)
    assert (ebac.permilles, ebac.permilles_30min, ebac.grams, ebac.burn_hours) == (0, 0, 0, 0)


def test_widmark_factor_differs_by_gender_and_height():
    male = SimpleNamespace(gender="mies", height=190, weight=90)
    female = SimpleNamespace(gender="nainen", height=190, weight=90)
    assert alcomath.widmark_factor(male) != alcomath.widmark_factor(female)
    assert alcomath.widmark_factor(male) != alcomath.widmark_factor(
        SimpleNamespace(gender="mies", height=180, weight=90)
    )


def test_alcohol_limit():
    assert not alcomath.is_alcohol_amount_out_of_limits(constants.SINGLE_DRINK_ALCOHOL_LIMIT)
    assert alcomath.is_alcohol_amount_out_of_limits(constants.SINGLE_DRINK_ALCOHOL_LIMIT + 1)
